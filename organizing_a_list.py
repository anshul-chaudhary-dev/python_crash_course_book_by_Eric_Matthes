# Organizing a list 

#sort() method
cars = ['bmw','audi','toyota','subaru']
print(cars)
cars.sort()
print(cars)


# sort(reverce=true)

print(cars)
cars.sort(reverse=True)
print(cars)


#sorting temporarily with the sorted() function

print(cars)
print(sorted(cars))
print(cars)



# reverse order 

print(cars)
cars.reverse()
print(cars)
# Note: The revers () method change the order of a list permanently, but you can revert the original order by applying revers() method to the same list a second time.



